def title(body, n=90):
    b = re.sub(r'^\s*\([^)]*\)\s*', '', body)
    m = re.search(r'\*\*(.+?)\*\*', b)
    t = (m.group(1) if m else b)
    t = re.sub(r'\*\*', '', t).split(' — المطلوب:')[0].replace('|', '¦').replace('\n', ' ').strip()
    return t if len(t) <= n else t[:n].rstrip() + ' …'

